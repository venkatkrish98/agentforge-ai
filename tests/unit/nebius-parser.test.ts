import { describe, it, expect } from "vitest";
import { stripThinkingBlocks, extractJsonFromResponse } from "@/lib/nebius/parser";

describe("Nebius Output Parser & Reasoning Tag Stripper", () => {
  it("strips <think> tags generated by reasoning models", () => {
    const raw = `<think>
Let's analyze the zero division bug.
We must throw an error with DivisionByZeroError.
</think>
{"status": "ok"}`;

    const stripped = stripThinkingBlocks(raw);
    expect(stripped).toBe('{"status": "ok"}');
  });

  it("extracts clean JSON from markdown code block", () => {
    const raw = `Here is the patch you requested:
\`\`\`json
{
  "rationale": "Repaired division by zero",
  "filesToModify": []
}
\`\`\`
Hope this helps!`;

    const parsed = extractJsonFromResponse(raw);
    expect(parsed.data).toBeDefined();
    expect(parsed.data.rationale).toBe("Repaired division by zero");
    expect(parsed.data.filesToModify).toEqual([]);
  });

  it("recovers JSON embedded in conversational text without code fence", () => {
    const raw = `Analysis complete. Result: {"message": "success", "count": 42}`;
    const parsed = extractJsonFromResponse(raw);
    expect(parsed.data).toBeDefined();
    expect(parsed.data.message).toBe("success");
    expect(parsed.data.count).toBe(42);
  });

  it("returns descriptive error on completely malformed response", () => {
    const raw = `This is plain text with no valid JSON brackets at all.`;
    const parsed = extractJsonFromResponse(raw);
    expect(parsed.data).toBeNull();
    expect(parsed.error).toContain("Failed to extract valid JSON");
  });
});
